"""Translate method signatures into message model source code."""

from __future__ import annotations

import inspect
import re
import subprocess
import sys
from collections.abc import Callable, Iterable, Mapping, Sequence
from dataclasses import dataclass
from types import NoneType, UnionType
from typing import (
    TYPE_CHECKING,
    Annotated,
    Literal,
    TypeAliasType,
    Union,
    get_args,
    get_origin,
    get_type_hints,
)

from .config import LIVE_ONLY, METADATA, WIRE_TYPES, Symbol, symbol

if TYPE_CHECKING:
    from .config import MessageSpec

type Convert = Callable[[str], str]

__HEADER = (
    "# This file is generated by `python -m opencosmo.serde.codegen`. Do not edit.\n"
    "# Change the method signatures or opencosmo/serde/codegen/config.py instead.\n"
)
__SERDE = "opencosmo.serde"


@dataclass(frozen=True)
class Wire:
    """Wire annotation source, its imports, and the conversion back to live values.

    ``convert`` maps the source of an expression holding a validated wire value
    to the source of an expression producing the live value.
    """

    source: str
    imports: frozenset[Symbol]
    convert: Convert | None = None

    @property
    def key(self) -> tuple[str, str | None]:
        return self.source, None if self.convert is None else self.convert("_")


def __named(name: Symbol, to_live: Symbol | None) -> Wire:
    imports = {name} if name.module != "builtins" else set()
    if to_live is None:
        return Wire(name.name, frozenset(imports))
    imports.add(to_live)
    return Wire(name.name, frozenset(imports), lambda value: f"{to_live.name}({value})")


def __lookup(annotation: object) -> Wire | None:
    try:
        wire_type = WIRE_TYPES.get(annotation)
    except TypeError:
        return None
    return (
        None if wire_type is None else __named(wire_type.annotation, wire_type.to_live)
    )


def __sequence(element: Wire, depth: int) -> Wire:
    convert = element.convert
    item = f"v{depth}"
    return Wire(
        f"tuple[{element.source}, ...]",
        element.imports,
        None
        if convert is None
        else lambda value: f"tuple({convert(item)} for {item} in {value})",
    )


def __mapping(key: Wire, value: Wire, depth: int) -> Wire:
    if key.convert is None and value.convert is None:
        convert = None
    else:
        to_key = key.convert or (lambda item: item)
        to_value = value.convert or (lambda item: item)
        k, v = f"k{depth}", f"v{depth}"

        def convert(source: str) -> str:
            return f"{{{to_key(k)}: {to_value(v)} for {k}, {v} in {source}.items()}}"

    return Wire(
        f"dict[{key.source}, {value.source}]", key.imports | value.imports, convert
    )


def __union(annotation: object, members: list[Wire]) -> Wire:
    unique = list({member.key: member for member in members}.values())
    if not unique:
        raise TypeError(f"No member of {annotation!r} can be serialized")
    if len(unique) == 1:
        return unique[0]
    source = " | ".join(member.source for member in unique)
    imports = frozenset().union(*(member.imports for member in unique))
    converted = [member for member in unique if member.convert is not None]
    if not converted:
        return Wire(source, imports)
    if (
        len(converted) == 1
        and len(unique) == 2
        and any(m.source == "None" for m in unique)
    ):
        convert = converted[0].convert
        assert convert is not None
        return Wire(
            source,
            imports,
            lambda value: f"None if {value} is None else {convert(value)}",
        )
    raise TypeError(
        f"Members of {annotation!r} convert differently; add the whole union to "
        "WIRE_TYPES"
    )


def __metadata(value: object) -> Wire:
    if type(value) not in METADATA:
        raise TypeError(f"Unsupported annotation metadata {value!r}")
    return Wire(repr(value), frozenset({symbol(type(value))}))


def __wire(annotation: object, depth: int = 0) -> Wire:
    if (known := __lookup(annotation)) is not None:
        return known
    if annotation in LIVE_ONLY:
        raise TypeError(f"{annotation!r} can only be passed as a live value")
    if isinstance(annotation, TypeAliasType):
        return __wire(annotation.__value__, depth)
    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is Annotated:
        inner = __wire(args[0], depth)
        metadata = [__metadata(value) for value in args[1:]]
        return Wire(
            f"Annotated[{', '.join([inner.source, *(m.source for m in metadata)])}]",
            inner.imports.union(*(m.imports for m in metadata))
            | {Symbol("typing", "Annotated")},
            inner.convert,
        )
    if origin is Literal:
        if not all(isinstance(arg, str | int | bool) for arg in args):
            raise TypeError(f"Unsupported literal values in {annotation!r}")
        return Wire(
            f"Literal[{', '.join(repr(arg) for arg in args)}]",
            frozenset({Symbol("typing", "Literal")}),
        )
    if origin in (Union, UnionType):
        members = [__wire(arg, depth) for arg in args if arg not in LIVE_ONLY]
        return __union(annotation, members)
    if origin in (Iterable, Sequence, list) or (
        origin is tuple and len(args) == 2 and args[1] is Ellipsis
    ):
        return __sequence(__wire(args[0], depth + 1), depth)
    if origin in (dict, Mapping):
        return __mapping(__wire(args[0], depth + 1), __wire(args[1], depth + 1), depth)
    raise TypeError(f"No wire representation for {annotation!r}")


def __default(parameter: inspect.Parameter) -> str | None:
    value = parameter.default
    if value is inspect.Parameter.empty:
        return None
    if not isinstance(value, str | int | float | bool | NoneType):
        raise TypeError(f"Unsupported default {value!r}")
    return repr(value)


@dataclass(frozen=True)
class GeneratedField:
    """One generated model field and the call argument it becomes."""

    declaration: str
    argument: str
    imports: frozenset[Symbol]


def __field(name: str, parameter: inspect.Parameter, hint: object) -> GeneratedField:
    attribute = f"self.{name}"
    annotated = Symbol("typing", "Annotated")
    match parameter.kind:
        case inspect.Parameter.VAR_POSITIONAL:
            wire = __sequence(__wire(hint, 1), 0)
            marker = Symbol(f"{__SERDE}.params", "VarArgs")
            value = wire.convert(attribute) if wire.convert else attribute
            return GeneratedField(
                f"{name}: Annotated[{wire.source}, VarArgs()] = ()",
                f"*{value}",
                wire.imports | {annotated, marker},
            )
        case inspect.Parameter.VAR_KEYWORD:
            keyword = Symbol(f"{__SERDE}.common", "Keyword")
            wire = __mapping(__named(keyword, None), __wire(hint, 1), 0)
            marker = Symbol(f"{__SERDE}.params", "VarKwargs")
            value = wire.convert(attribute) if wire.convert else attribute
            return GeneratedField(
                f"{name}: Annotated[{wire.source}, VarKwargs()] = "
                "Field(default_factory=dict)",
                f"**{value}",
                wire.imports | {annotated, marker, Symbol("pydantic", "Field")},
            )
    wire = __wire(hint)
    value = wire.convert(attribute) if wire.convert else attribute
    default = __default(parameter)
    suffix = "" if default is None else f" = {default}"
    if parameter.kind is inspect.Parameter.KEYWORD_ONLY:
        marker = Symbol(f"{__SERDE}.params", "KeywordOnly")
        return GeneratedField(
            f"{name}: Annotated[{wire.source}, KeywordOnly()]{suffix}",
            f"{name}={value}",
            wire.imports | {annotated, marker},
        )
    return GeneratedField(f"{name}: {wire.source}{suffix}", value, wire.imports)


def class_name(spec: MessageSpec, method: str) -> str:
    """The name of the message class generated for ``method``."""
    return f"{spec.target.__name__}{method.title().replace('_', '')}Message"


def __message(spec: MessageSpec, method: str) -> tuple[str, frozenset[Symbol]]:
    target = spec.target.__name__
    function = getattr(spec.target, method)
    try:
        hints = get_type_hints(
            function, localns=dict(spec.namespace), include_extras=True
        )
    except NameError as error:
        raise TypeError(f"{target}.{method}: {error}; add it to namespace") from error
    fields: list[GeneratedField] = []
    for name, parameter in list(inspect.signature(function).parameters.items())[1:]:
        if name not in hints:
            raise TypeError(f"{target}.{method}({name}) has no annotation")
        try:
            fields.append(__field(name, parameter, hints[name]))
        except TypeError as error:
            raise TypeError(f"{target}.{method}({name}): {error}") from error

    imports = frozenset(
        {
            Symbol(f"{__SERDE}.expression", "ExpressionModel"),
            Symbol("typing", "ClassVar"),
            Symbol("typing", "Literal"),
        }
    ).union(*(f.imports for f in fields))
    lines = [
        f"class {class_name(spec, method)}(ExpressionModel):",
        f'    """A call to :meth:`{spec.public_name}.{method}`."""',
        "",
        f'    kind: Literal["{method}"] = "{method}"',
        f'    method: ClassVar[str] = "{method}"',
        *(f"    {f.declaration}" for f in fields),
    ]
    names = {name for name in inspect.signature(function).parameters}
    for check in spec.checks.get(method, ()):
        if unknown := set(check.fields) - names:
            raise ValueError(f"{check.function.name} uses unknown fields {unknown}")
        arguments = ", ".join(f"self.{name}" for name in check.fields)
        lines += [
            "",
            '    @model_validator(mode="after")',
            f"    def check_{check.function.name}(self) -> Self:",
            f'        """Validate this message with ``{check.function.name}``."""',
            f"        {check.function.name}({arguments})",
            "        return self",
        ]
        imports |= {
            check.function,
            Symbol("pydantic", "model_validator"),
            Symbol("typing", "Self"),
        }
    arguments = ", ".join(f.argument for f in fields)
    lines += [
        "",
        f"    def apply(self, target: {target}) -> {target}:",
        f'        """Call ``{target}.{method}`` with the arguments in this message."""',
        f"        return target.{method}({arguments})",
    ]
    return "\n".join(lines), imports


def __imports(imports: Iterable[Symbol]) -> str:
    modules: dict[str, set[str]] = {}
    for item in imports:
        modules.setdefault(item.module, set()).add(item.name)
    return "\n".join(
        f"from {module} import {', '.join(sorted(names))}"
        for module, names in sorted(modules.items())
    )


def __ruff(source: str, spec: MessageSpec, *arguments: str) -> str:
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            *arguments,
            "--stdin-filename",
            str(spec.output),
        ],
        input=source,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(f"ruff rejected generated source:\n{result.stderr}")
    return result.stdout


def __format(source: str, spec: MessageSpec) -> str:
    sorted_source = __ruff(source, spec, "check", "--select", "I", "--fix", "-")
    return __ruff(sorted_source, spec, "format", "-")


def render(spec: MessageSpec) -> str:
    """Render the message module for ``spec`` as formatted Python source.

    Raises
    ------
    TypeError
        If a parameter's annotation, metadata, or default has no wire form.
    ValueError
        If checks are configured for unexposed methods or unknown fields.
    """
    if unknown := set(spec.checks) - set(spec.methods):
        raise ValueError(f"Checks provided for unexposed methods {sorted(unknown)}")
    target = spec.target.__name__
    classes: list[str] = []
    imports: set[Symbol] = {Symbol("typing", "TYPE_CHECKING")}
    for method in spec.methods:
        source, needed = __message(spec, method)
        classes.append(source)
        imports |= needed
    names = [class_name(spec, method) for method in spec.methods]
    union = f"{target}Message"
    types = f"{re.sub(r'(?<!^)(?=[A-Z])', '_', target).upper()}_MESSAGE_TYPES"
    imports |= {Symbol("typing", "Annotated"), Symbol("pydantic", "Field")}
    module = "\n\n\n".join(
        [
            (
                f'{__HEADER}"""Messages for :class:`{spec.public_name}` operations."""'
                "\n\nfrom __future__ import annotations\n\n"
                f"{__imports(imports)}\n\n"
                "if TYPE_CHECKING:\n"
                f"    {__imports([symbol(spec.target)])}"
            ),
            *classes,
            (
                f"type {union} = Annotated[\n    {' | '.join(names)},\n"
                '    Field(discriminator="kind"),\n]'
            ),
            f"{types} = ({', '.join(names)},)",
            f"__all__ = {sorted([*names, union, types])!r}\n",
        ]
    )
    return __format(module, spec)


__all__ = ["class_name", "render"]
